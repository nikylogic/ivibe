// Rebuilds src/mascot-svg.ts from the logo: the mascot without its eyes and mouth, which
// src/mascot.tsx draws so they can move. Run from apps/video: node scripts/mascot-svg.mjs
import { readFileSync, writeFileSync } from "node:fs";

const svg = readFileSync("../../logo/web/logo-light.svg", "utf8");
const inner = svg
  .replace(/^[\s\S]*?<svg[^>]*>/, "")
  .replace(/<\/svg>\s*$/, "")
  .replace(/<title>[\s\S]*?<\/title>/, "")
  .replace(/\s*<ellipse[^>]*\/>/g, "")
  .replace(/\s*<path d="M617 851[^>]*\/>/, "");
writeFileSync(
  "src/mascot-svg.ts",
  `// SPDX-License-Identifier: AGPL-3.0-only
// Generated by scripts/mascot-svg.mjs from logo/web/logo-light.svg, without its eyes and mouth.

export const MASCOT_VIEWBOX = "205 190 1040 1040";
export const MASCOT_BODY = ${JSON.stringify(inner.trim())};
`,
);
